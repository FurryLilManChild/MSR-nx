#!/usr/bin/env python3
"""MSR-nx: builds the renderer's own shaders and embeds them in nxout/dk_shaders.h.

Run inside the devkitA64 image (uam is at /opt/devkitpro/tools/bin/uam), from the build folder W,
with the repository's runtime folder at R:  python3 mkshaders.py <R> <W>

pica_vsh.glsl and pica_fsh.glsl are the general (interpreter) shaders. The VRAM compute shaders are
made from runtime/gpu/dk/vram_ops.inc: one small wrapper per kernel (k_fill, k_copy, ...), so the
code the GPU runs is the code tools/tests/vram_ops_test.cpp checks on the CPU.
"""
import os
import subprocess
import sys

UAM = '/opt/devkitpro/tools/bin/uam'
KERNELS = ['fill', 'copy', 'transfer', 'store', 'load', 'texdecode', 'screen']

WRAPPER = '''#version 460
// generated by tools/switch/mkshaders.py around vram_ops.inc: not hand-edited
layout (local_size_x = 64) in;
layout (std430, binding = 0) buffer Vram { uint vram[]; };
layout (std430, binding = 1) buffer Out { uint outw[]; };
layout (std140, binding = 0) uniform Params { uvec4 q[4]; };
layout (binding = 0) uniform sampler2D src_img;
layout (binding = 0, rgba8) uniform writeonly image2D dst_img;
#define LDW(i) vram[(i)]
#define STW(i, v) vram[(i)] = (v)
#define IMG_READ(x, y) packUnorm4x8(texelFetch(src_img, ivec2(int(x), int(y)), 0))
#define IMG_WRITE(x, y, v) imageStore(dst_img, ivec2(int(x), int(y)), unpackUnorm4x8(v))
#define OUTW(i, v) outw[(i)] = (v)
%s
void main() { k_%s(gl_GlobalInvocationID.x); }
'''


def main():
    R, W = sys.argv[1], sys.argv[2]
    out_dir = os.path.join(W, 'nxout')
    os.makedirs(out_dir, exist_ok=True)
    jobs = [('pica_vsh', 'vert', os.path.join(R, 'gpu/dk/pica_vsh.glsl')),
            ('pica_fsh', 'frag', os.path.join(R, 'gpu/dk/pica_fsh.glsl')),
            ('selftest_vsh', 'vert', os.path.join(R, 'gpu/dk/test/selftest_vsh.glsl')),
            ('pica_fsh_test8', 'frag', os.path.join(R, 'gpu/dk/test/pica_fsh_test8.glsl'))]
    inc = open(os.path.join(R, 'gpu/dk/vram_ops.inc')).read()
    for k in KERNELS:
        src = os.path.join(out_dir, 'vram_%s.glsl' % k)
        open(src, 'w').write(WRAPPER % (inc, k))
        jobs.append(('vram_' + k, 'comp', src))
    out = ['// generated from the .dksh files built by uam; not hand-edited', '#pragma once', '#include <stdint.h>']
    for name, stage, src in jobs:
        dksh = os.path.join(out_dir, name + '.dksh')
        subprocess.run([UAM, '-s', stage, '-o', dksh, src], check=True)
        d = open(dksh, 'rb').read()
        out.append('static const uint8_t %s_dksh[] __attribute__((aligned(256))) = {%s};' % (name, ','.join(str(b) for b in d)))
        out.append('static const uint32_t %s_dksh_size = %d;' % (name, len(d)))
    open(os.path.join(out_dir, 'dk_shaders.h'), 'w').write('\n'.join(out) + '\n')
    print('%d shaders' % len(jobs))


if __name__ == '__main__':
    main()
